"""Post-release collect set-down PUSH-IN: nudge the free carton inboard off the +x lip
(sim-place-post-release-push-in-v1).

PR 385 lands the side-grip carton on the Rollwagen upper shelf with a mouth-out lip overhang: at the
``housing_seat_lip_overhang_m`` 0.28 seat the carton rests with only ~47 % of its base on the shelf and its
centre of mass ~14 mm inboard of the +x lip -- a close-to-tipping rest that is visually wrong on camera and
at risk during the tow. This module is the PURE / CPU core of the opt-in fix: after the PR 382 seat gate
releases the carton and the gripper backs clear, re-contact the free carton's lip-facing (+x) face with the
suction pad at (or below) its mid-height and push it inboard (cart -x) to a more centred rest, then back the
pad out and lift clear; the stage continues as today.

Honest geometric limit (measured against the composed coldwin100 cart, usd-core;
``data/sim-place-post-release-push-in-v1/report.md``): the side-grip suction HOUSING
(``cube_without_surface_plates``) is COAXIAL with the pad normal and hangs ~0.14 m below the carton bottom,
so it cannot follow the carton inboard over the shelf board -- it strikes the board after only ~41 mm of
push (penetration onset), while a fully-centred rest needs ~369 mm. (A 180 deg wrist roll about the pad
normal does NOT lift it: the housing centroid sits on that axis, so rolling only spins it in place.) So the
push is a BOUNDED nudge: the stroke is capped so the housing keeps a configured clearance (default 10 mm) to
the shelf board, which triples the +x-lip CoM margin (0.28 seat: ~14 mm -> ~44 mm inboard) without striking
the board. A CENTRED rest needs a TOP-DOWN grip (hangs the housing ABOVE the carton) -- the follow-up, out of
scope here.

The arm configs are generated by :func:`carton_level.level_place_ik` (the carton kept level throughout, so a
level FREE carton is pushed flat and never tipped), the stroke cap is found with an INJECTED housing-vs-shelf
clearance closure (the host wires the PR 383 shelf-inclusive XRDF arm-sphere sweep), and the predicted tilt
is read straight from the FK up-axis so the caller can prove it stays inside the 2.0 deg bound. Pure numpy +
the URDF FK; no Isaac / ROS / GPU. The composed-USD replay + per-waypoint housing/wrist/cage/deck gaps live
in ``scripts/check_push_in_descent.py``; unit tests in ``scripts/twin/tests/test_push_in.py``.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Callable, List, Optional, Sequence, Tuple

import numpy as np

# Log tokens the controller prints.
PLACE_PUSH_IN = 'PLACE_PUSH_IN'
PLACE_PUSH_IN_REJECTED = 'PLACE_PUSH_IN_REJECTED'

# Default push-in knobs (metres / count), mirrored by the LevelConfig defaults.
DEFAULT_SHELF_CLEAR_MIN_M = 0.010     # the housing must keep >= this to the shelf board through the stroke
DEFAULT_STANDOFF_M = 0.08             # the above-contact vertical standoff the pad descends from / lifts to
DEFAULT_BACKOUT_M = 0.06              # the lateral (+x, outboard) back-off before the clearing lift
DEFAULT_WAYPOINTS = 6                 # per-leg densification for the approach / stroke / retreat
DEFAULT_SETTLE_M = 0.010             # the achieved-vs-expected CoM tolerance for the done/short verdict


@dataclass
class PushInGeometry:
    """The live cart geometry the controller's push-in dispatch needs, installed at boot by
    ``place_cage_wiring.wire_push_in`` (so the controller hook stays ``None`` => byte-identical when the
    feature is off). Pure data + closures -- no Isaac / ROS:

      * ``push_dir_base`` -- the unit inboard push direction (cart -x) in ur_base_link.
      * ``shelf_clear_fn`` -- ``configs -> min housing-vs-shelf clearance (m)`` (the PR 383 shelf-inclusive
        XRDF arm-sphere sweep), the stroke-cap criterion.
      * ``carton_com_cart_x`` -- ``config -> carton CoM cart-x (m)``, so the controller turns the configured
        ``push_in_target_x_m`` into a stroke from the live seat.
    """
    push_dir_base: np.ndarray
    shelf_clear_fn: Callable[[List[list]], float]
    carton_com_cart_x: Callable[[list], float]
    carton_support_fraction: Optional[Callable[[list], float]] = None
    meta: dict = field(default_factory=dict)


def clip_area(poly, lo, hi):
    """Area of a convex polygon ``poly`` (list of (x, y)) clipped to the AABB ``[lo, hi]`` (2-D), by
    Sutherland-Hodgman -- the carton-base-on-shelf overlap for ``support_fraction``. Pure/CPU."""
    def _ix(a, b, ax, val):
        t = (val - a[ax]) / (b[ax] - a[ax])
        return (a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1]))
    pts = list(poly)
    edges = [(lambda p: p[0] >= lo[0], lambda a, b: _ix(a, b, 0, lo[0])),
             (lambda p: p[0] <= hi[0], lambda a, b: _ix(a, b, 0, hi[0])),
             (lambda p: p[1] >= lo[1], lambda a, b: _ix(a, b, 1, lo[1])),
             (lambda p: p[1] <= hi[1], lambda a, b: _ix(a, b, 1, hi[1]))]
    for inside, inter in edges:
        out = []
        for i in range(len(pts)):
            a, b = pts[i], pts[(i + 1) % len(pts)]
            ina, inb = inside(a), inside(b)
            if ina:
                out.append(a)
            if ina != inb:
                out.append(inter(a, b))
        pts = out
        if not pts:
            return 0.0
    area = 0.0
    for i in range(len(pts)):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % len(pts)]
        area += x1 * y2 - x2 * y1
    return abs(area) / 2.0


def push_direction_base(T_base_cart) -> np.ndarray:
    """The unit INBOARD push direction (cart -x) expressed in ur_base_link, from the cart-body ->
    ur_base_link transform. The rollwagen docks with its open +x mouth toward the robot, so pushing the
    carton off the +x lip means driving the pad along cart -x. Pure/CPU."""
    R = np.asarray(T_base_cart, float)[:3, :3]
    d = -(R @ np.array([1.0, 0.0, 0.0]))
    n = float(np.linalg.norm(d))
    if n <= 1e-9:
        raise ValueError('push_direction_base: degenerate cart transform (no cart +x axis)')
    return d / n


@dataclass
class PushInPlan:
    """The planned post-release push-in motion.

    ``waypoints`` is the single ARM-order joint path the controller dispatches: approach (standoff ->
    contact) + stroke (contact -> capped inboard) + retreat (back-out + clearing lift). ``approach`` /
    ``stroke`` / ``retreat`` are the three legs (views into ``waypoints``) the CPU proof reports per-leg
    gaps for. ``target_stroke_m`` is what the caller asked for; ``achieved_stroke_m`` is what the shelf-
    clearance cap allowed (``capped`` True when the cap shortened it). ``max_tilt_deg`` is the worst FK
    carton tilt over the whole motion (must stay <= the 2.0 deg bound). ``contact_config`` is the re-contact
    pose; ``expected_com_shift_m`` is how far the carton CoM should move (= achieved_stroke_m along cart -x)."""
    waypoints: List[list]
    approach: List[list]
    stroke: List[list]
    retreat: List[list]
    contact_config: list
    target_stroke_m: float
    achieved_stroke_m: float
    capped: bool
    max_tilt_deg: float
    shelf_clear_min_m: float = DEFAULT_SHELF_CLEAR_MIN_M
    expected_com_shift_m: float = 0.0
    meta: dict = field(default_factory=dict)


def _level_cfg(robot, target_pos, up_in_tool, seed, *, tool_link, root, limits):
    from . import carton_level as cl
    from .cad_tool import ARM_JOINTS
    sol = cl.level_place_ik(robot, target_pos, up_in_tool, seed, tool_link=tool_link, root=root,
                            limits=limits, fast=True)
    return [float(sol[j]) for j in ARM_JOINTS]


def _carton_tilt_deg(robot, config, up_in_tool, *, tool_link, root, base_R=None):
    """The carton up-axis tilt (deg off world +Z) at ``config`` -- the FK prediction the caller proves
    stays inside the 2.0 deg bound. Mirrors ``carton_level``'s level residual."""
    from . import carton_level as cl
    from .cad_tool import ARM_JOINTS
    cfg = {j: float(config[i]) for i, j in enumerate(ARM_JOINTS)} if not isinstance(config, dict) else dict(config)
    T = cl.tool_transform(robot, cfg, tool_link, root)
    uw = np.asarray(T, float)[:3, :3] @ np.asarray(up_in_tool, float)
    if base_R is not None:
        uw = np.asarray(base_R, float) @ uw
    uw = uw / (np.linalg.norm(uw) or 1.0)
    return math.degrees(math.acos(max(-1.0, min(1.0, float(uw[2])))))


def _solve_leg(robot, tcp_from, tcp_to, up_in_tool, seed, *, n, tool_link, root, limits):
    """``n`` level configs interpolating the TCP from ``tcp_from`` to ``tcp_to`` (exclusive of the start,
    inclusive of the end), seeded continuously from ``seed``. Raises ValueError if any waypoint is
    unreachable-while-level (the honest 'the pad cannot reach there' signal)."""
    a = np.asarray(tcp_from, float)[:3]
    b = np.asarray(tcp_to, float)[:3]
    out = []
    cur = list(seed)
    for i in range(1, int(n) + 1):
        tgt = (a + (b - a) * (i / float(n))).tolist()
        cur = _level_cfg(robot, tgt, up_in_tool, cur, tool_link=tool_link, root=root, limits=limits)
        out.append(cur)
    return out


def stroke_cap_m(robot, contact_config, contact_tcp, up_in_tool, push_dir_base, *, target_stroke_m,
                 shelf_clear_min_m, shelf_clear_fn, waypoints, tool_link, root, limits):
    """The largest inboard stroke (<= ``target_stroke_m``) whose swept pad configs keep the housing
    ``>= shelf_clear_min_m`` from the shelf board, via the INJECTED ``shelf_clear_fn`` (a closure
    ``configs -> min housing-vs-shelf clearance (m)`` -- the host wires PR 383's shelf-inclusive XRDF
    arm-sphere sweep; a CPU test injects an analytic stub). ``shelf_clear_fn`` None => no cap (the full
    target). Binary-searches the stroke so the final + intermediate configs all clear. Pure/CPU."""
    target = max(0.0, float(target_stroke_m))
    if shelf_clear_fn is None or target <= 0.0:
        return target

    def clears(stroke):
        if stroke <= 0.0:
            return True
        tcp_end = np.asarray(contact_tcp, float)[:3] + np.asarray(push_dir_base, float) * stroke
        cfgs = _solve_leg(robot, contact_tcp, tcp_end, up_in_tool, contact_config,
                          n=waypoints, tool_link=tool_link, root=root, limits=limits)
        try:
            return float(shelf_clear_fn(cfgs)) >= float(shelf_clear_min_m)
        except Exception:
            return False

    if clears(target):
        return target
    lo, hi = 0.0, target
    for _ in range(24):
        mid = (lo + hi) / 2.0
        if clears(mid):
            lo = mid
        else:
            hi = mid
    return lo


def plan_push_in(robot, seat_tcp, up_in_tool, start_config, push_dir_base, *, target_stroke_m,
                 shelf_clear_min_m=DEFAULT_SHELF_CLEAR_MIN_M, shelf_clear_fn=None,
                 standoff_m=DEFAULT_STANDOFF_M, backout_m=DEFAULT_BACKOUT_M, waypoints=DEFAULT_WAYPOINTS,
                 bound_deg=2.0, tool_link='ur_tool0', root='ur_base_link', limits=None):
    """Plan the post-release push-in: re-contact the carton at ``seat_tcp`` (the PR 385 housing-compatible
    seat tool-origin), push it inboard along ``push_dir_base`` (cart -x in ur_base_link) by up to
    ``target_stroke_m`` -- capped so the housing keeps ``shelf_clear_min_m`` to the shelf board
    (:func:`stroke_cap_m`) -- then back the pad out ``backout_m`` and lift ``standoff_m`` clear.

    The pad is kept carton-level throughout (:func:`carton_level.level_place_ik`), so a level free carton is
    pushed flat and never tipped; the contact is at the grip TCP (the carton's lower side face, at/below
    mid-height). ``start_config`` is the current (release-lifted) arm pose the approach departs from.
    Returns a :class:`PushInPlan`; raises ``ValueError`` when the pad cannot reach the contact / standoff
    while level (the honest 'push-in pose unreachable' signal the controller fails by name)."""
    seat = np.asarray(seat_tcp, float)[:3]
    pdir = np.asarray(push_dir_base, float)
    pdir = pdir / (float(np.linalg.norm(pdir)) or 1.0)
    standoff_tcp = seat + np.array([0.0, 0.0, float(standoff_m)])

    # Re-contact pose (the carton face at the seat) + the above-contact standoff, seeded from the lifted start.
    contact_config = _level_cfg(robot, seat.tolist(), up_in_tool, list(start_config),
                                tool_link=tool_link, root=root, limits=limits)
    standoff_config = _level_cfg(robot, standoff_tcp.tolist(), up_in_tool, list(start_config),
                                 tool_link=tool_link, root=root, limits=limits)

    cap = stroke_cap_m(robot, contact_config, seat.tolist(), up_in_tool, pdir,
                       target_stroke_m=target_stroke_m, shelf_clear_min_m=shelf_clear_min_m,
                       shelf_clear_fn=shelf_clear_fn, waypoints=waypoints, tool_link=tool_link,
                       root=root, limits=limits)
    capped = cap < float(target_stroke_m) - 1e-6

    # Approach: start -> standoff(above) -> contact.
    approach = [standoff_config]
    approach += _solve_leg(robot, standoff_tcp.tolist(), seat.tolist(), up_in_tool, standoff_config,
                           n=waypoints, tool_link=tool_link, root=root, limits=limits)
    # Stroke: contact -> contact + pdir*cap.
    stroke: List[list] = []
    end_tcp = seat.copy()
    if cap > 0.0:
        end_tcp = seat + pdir * cap
        stroke = _solve_leg(robot, seat.tolist(), end_tcp.tolist(), up_in_tool, approach[-1],
                            n=waypoints, tool_link=tool_link, root=root, limits=limits)
    # Retreat: back out (-pdir) then lift (+z).
    back_tcp = end_tcp - pdir * float(backout_m)
    seed = stroke[-1] if stroke else approach[-1]
    retreat = _solve_leg(robot, end_tcp.tolist(), back_tcp.tolist(), up_in_tool, seed,
                         n=waypoints, tool_link=tool_link, root=root, limits=limits)
    lift_tcp = back_tcp + np.array([0.0, 0.0, float(standoff_m)])
    retreat += _solve_leg(robot, back_tcp.tolist(), lift_tcp.tolist(), up_in_tool, retreat[-1],
                          n=waypoints, tool_link=tool_link, root=root, limits=limits)

    waypoints_all = approach + stroke + retreat
    max_tilt = max(_carton_tilt_deg(robot, c, up_in_tool, tool_link=tool_link, root=root)
                   for c in waypoints_all)
    return PushInPlan(
        waypoints=waypoints_all, approach=approach, stroke=stroke, retreat=retreat,
        contact_config=contact_config, target_stroke_m=float(target_stroke_m), achieved_stroke_m=float(cap),
        capped=capped, max_tilt_deg=float(max_tilt), shelf_clear_min_m=float(shelf_clear_min_m),
        expected_com_shift_m=float(cap),
        meta={'bound_deg': float(bound_deg), 'standoff_m': float(standoff_m), 'backout_m': float(backout_m)})


def classify_result(expected_shift_m, measured_shift_m, *, settle_m=DEFAULT_SETTLE_M):
    """``('done'|'short', reason)`` from the expected vs measured carton CoM inboard shift. ``done`` when
    the carton moved within ``settle_m`` of the expected (capped) stroke; ``short`` otherwise (the carton
    did not track the push -- a slipped pad / under-travel -- which the controller logs by name and retries
    at most once). Pure/CPU."""
    gap = float(expected_shift_m) - float(measured_shift_m)
    if abs(gap) <= float(settle_m):
        return 'done', ('carton tracked the push within %.1f mm of the %.1f mm expected inboard shift'
                        % (abs(gap) * 1000.0, float(expected_shift_m) * 1000.0))
    return 'short', ('carton moved %.1f mm inboard vs the %.1f mm expected (%.1f mm short of the capped '
                     'stroke)' % (float(measured_shift_m) * 1000.0, float(expected_shift_m) * 1000.0,
                                  gap * 1000.0))
